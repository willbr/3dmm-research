"""Extract original RT_DIALOG templates from a compiled .res into SDK-free C++.

Run after changing .rc dialogs, using the Windows SDL build's .res output.
The generated source is checked in so Mac/Linux need no Windows resource compiler.
"""
import argparse
import pathlib
import struct


def dialogs(data):
    offset = 0
    while offset < len(data):
        count, header = struct.unpack_from('<II', data, offset)
        if header < 8 or header > len(data) - offset or count > len(data) - offset - header:
            raise ValueError('invalid resource bounds')
        cursor = offset + 8

        def name():
            nonlocal cursor
            first = struct.unpack_from('<H', data, cursor)[0]
            cursor += 2
            if first == 0xffff:
                result = struct.unpack_from('<H', data, cursor)[0]
                cursor += 2
                return result
            while first:
                first = struct.unpack_from('<H', data, cursor)[0]
                cursor += 2
            return None

        kind, identifier = name(), name()
        if kind == 5 and identifier is not None:
            yield identifier, data[offset + header:offset + header + count]
        offset = (offset + header + count + 3) & ~3


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('resource', type=pathlib.Path)
    parser.add_argument('output', type=pathlib.Path)
    parser.add_argument('--check', action='store_true', help='Fail if the checked-in bundle differs; write nothing')
    args = parser.parse_args()
    records = sorted(dialogs(args.resource.read_bytes()))
    if not records or len({key for key, _ in records}) != len(records):
        raise ValueError('missing or duplicate dialog IDs')
    lines = ['/* Copyright (c) Microsoft Corporation. Licensed under the MIT License. */',
             '// Generated by tools/embed-dialog-resources.py from original .rc templates.',
             '// Regenerate from the Windows SDL build after editing dialog resources.',
             '// clang-format off',
             '// Generated template bytes and their lookup table.',
             '#include "dialog_resources.h"', 'namespace {']
    for key, payload in records:
        lines.append('const unsigned char dialog%d[] = {' % key)
        for offset in range(0, len(payload), 20):
            lines.append('    ' + ','.join('0x%02x' % b for b in payload[offset:offset + 20]) + ',')
        lines.append('};')
    lines += ['bool ReadDialogTemplate(std::uint32_t id, KauaiDialogs::Resource &resource) {', '    switch (id) {']
    for key, _ in records:
        lines.append('    case %d: return KauaiDialogs::ReadResource(dialog%d, sizeof(dialog%d), resource);' % (key, key, key))
    lines += ['    default: return false;', '    }', '}',
              'bool ReadDialog(std::uint32_t id, KauaiDialogs::Resource &resource) {',
              '    if (!ReadDialogTemplate(id, resource)) return false;',
              '    return true;', '}',
              'struct RegisterDialogs { RegisterDialogs() { KauaiDialogs::SetResourceProvider(ReadDialog); } } registerDialogs;',
              '} // namespace', '']
    generated = '\n'.join(lines)
    if args.check:
        if args.output.read_text(encoding='utf-8') != generated:
            raise SystemExit('Dialog bundle is stale: regenerate ' + str(args.output))
    else:
        args.output.write_text(generated, encoding='utf-8', newline='\n')
    print('Embedded %d original dialogs in %s' % (len(records), args.output))


if __name__ == '__main__':
    main()
